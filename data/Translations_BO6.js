// === ФУНКЦИИ ПЕРЕВОДА ДЛЯ BO6 ===
function translateBO6WeaponName(name) {
    if (!name) return name;
    return window.BO6_WEAPON_TRANSLATIONS?.[name] || name;
}

function translateBO6WeaponCategory(name) {
    if (!name) return name;
    return window.BO6_WEAPON_CATEGORY_TRANSLATIONS?.[name] || name;
}

function translateBO6AttachmentName(name) {
    if (!name) return name;
    return window.BO6_ATTACHMENT_TRANSLATIONS?.[name] || name;
}

function translateBO6CategoryName(name) {
    if (!name) return name;
    return window.BO6_CATEGORY_TRANSLATIONS?.[name] || name;
}

function translateBO6Class(classData) {
    if (!classData) return null;
    
    const translated = {
        primary: {
            name: translateBO6WeaponName(classData.primary?.name),
            category: classData.primary?.category,
            categoryName: translateBO6WeaponCategory(classData.primary?.categoryName) || classData.primary?.categoryName,
            attachments: []
        },
        secondary: {
            name: translateBO6WeaponName(classData.secondary?.name),
            category: classData.secondary?.category,
            categoryName: translateBO6WeaponCategory(classData.secondary?.categoryName) || classData.secondary?.categoryName,
            attachments: []
        }
    };
    
    if (classData.primary?.attachments && classData.primary.attachments.length > 0) {
        translated.primary.attachments = classData.primary.attachments.map(att => {
            if (att.id === 'no_attachments') {
                return { ...att, name: 'Нет доступных модулей' };
            }
            return {
                ...att,
                name: translateBO6AttachmentName(att.name)
            };
        });
    }
    
    if (classData.secondary?.attachments && classData.secondary.attachments.length > 0) {
        translated.secondary.attachments = classData.secondary.attachments.map(att => {
            if (att.id === 'no_attachments') {
                return { ...att, name: 'Нет доступных модулей' };
            }
            return {
                ...att,
                name: translateBO6AttachmentName(att.name)
            };
        });
    }
    
    return translated;
}

