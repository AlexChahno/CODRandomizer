// === ФУНКЦИИ ПЕРЕВОДА ДЛЯ BO7 ===
function translateBO7WeaponName(name) {
    if (!name) return name;
    return window.BO7_WEAPON_TRANSLATIONS?.[name] || name;
}

function translateBO7WeaponCategory(name) {
    if (!name) return name;
    return window.BO7_WEAPON_CATEGORY_TRANSLATIONS?.[name] || name;
}

function translateBO7AttachmentName(name) {
    if (!name) return name;
    return window.BO7_ATTACHMENT_TRANSLATIONS?.[name] || name;
}

function translateBO7CategoryName(name) {
    if (!name) return name;
    return window.BO7_CATEGORY_TRANSLATIONS?.[name] || name;
}

function translateBO7Class(classData) {
    if (!classData) return null;
    
    const translated = {
        primary: {
            name: translateBO7WeaponName(classData.primary?.name),
            category: classData.primary?.category,
            categoryName: translateBO7WeaponCategory(classData.primary?.categoryName) || classData.primary?.categoryName,
            attachments: []
        },
        secondary: {
            name: translateBO7WeaponName(classData.secondary?.name),
            category: classData.secondary?.category,
            categoryName: translateBO7WeaponCategory(classData.secondary?.categoryName) || classData.secondary?.categoryName,
            attachments: []
        }
    };
    
    if (classData.primary?.attachments && classData.primary.attachments.length > 0) {
        translated.primary.attachments = classData.primary.attachments.map(att => {
            if (att.id === 'no_attachments') {
                return { ...att, name: 'Нет доступных модулей' };
            }
            return {
                ...att,
                name: translateBO7AttachmentName(att.name)
            };
        });
    }
    
    if (classData.secondary?.attachments && classData.secondary.attachments.length > 0) {
        translated.secondary.attachments = classData.secondary.attachments.map(att => {
            if (att.id === 'no_attachments') {
                return { ...att, name: 'Нет доступных модулей' };
            }
            return {
                ...att,
                name: translateBO7AttachmentName(att.name)
            };
        });
    }
    
    return translated;
}

