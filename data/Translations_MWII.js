// === ФУНКЦИИ ПЕРЕВОДА ДЛЯ MWII ===
function translateMWIIWeaponName(name) {
    if (!name) return name;
    return window.MWII_WEAPON_TRANSLATIONS?.[name] || name;
}

function translateMWIIWeaponCategory(name) {
    if (!name) return name;
    return window.MWII_WEAPON_CATEGORY_TRANSLATIONS?.[name] || name;
}

function translateMWIIAttachmentName(name) {
    if (!name) return name;
    return window.MWII_ATTACHMENT_TRANSLATIONS?.[name] || name;
}

function translateMWIICategoryName(name) {
    if (!name) return name;
    return window.MWII_CATEGORY_TRANSLATIONS?.[name] || name;
}

function translateMWIIClass(classData) {
    if (!classData) return null;
    
    const translated = {
        primary: {
            name: translateMWIIWeaponName(classData.primary?.name),
            category: classData.primary?.category,
            categoryName: translateMWIIWeaponCategory(classData.primary?.categoryName) || classData.primary?.categoryName,
            attachments: []
        },
        secondary: {
            name: translateMWIIWeaponName(classData.secondary?.name),
            category: classData.secondary?.category,
            categoryName: translateMWIIWeaponCategory(classData.secondary?.categoryName) || classData.secondary?.categoryName,
            attachments: []
        }
    };
    
    if (classData.primary?.attachments && classData.primary.attachments.length > 0) {
        translated.primary.attachments = classData.primary.attachments.map(att => {
            if (att.id === 'no_attachments') {
                return { ...att, name: 'Нет доступных модулей' };
            }
            return {
                ...att,
                name: translateMWIIAttachmentName(att.name)
            };
        });
    }
    
    if (classData.secondary?.attachments && classData.secondary.attachments.length > 0) {
        translated.secondary.attachments = classData.secondary.attachments.map(att => {
            if (att.id === 'no_attachments') {
                return { ...att, name: 'Нет доступных модулей' };
            }
            return {
                ...att,
                name: translateMWIIAttachmentName(att.name)
            };
        });
    }
    
    return translated;
}

