// ---------- ФУНКЦИИ ДЛЯ ПОЛУЧЕНИЯ ДАННЫХ ----------
function getExtraItemsForGame(game, type) {
    const data = window.EXTRA_ITEMS[type];
    if (!data) return [];
    
    if (game === 'warzone') {
        const all = [];
        for (const g of ['bo6','bo7','mwii','mwiii']) {
            if (data[g]) {
                for (const item of data[g]) {
                    all.push({ ...item, game: g });
                }
            }
        }
        return all;
    }
    
    return (data[game] || []).map(item => ({ ...item, game: game }));
}

function getPerksForGame(game) {
    const perks = window.EXTRA_ITEMS.perks;
    if (game === 'warzone') {
        const combined = { perk1: [], perk2: [], perk3: [], tierA: [], tierB: [] };
        for (const g of ['bo6','bo7','mwii','mwiii']) {
            const p = perks[g];
            if (p) {
                for (const slot of ['perk1','perk2','perk3','tierA','tierB']) {
                    if (p[slot]) {
                        for (const item of p[slot]) {
                            combined[slot].push({ ...item, game: g });
                        }
                    }
                }
            }
        }
        for (const slot of ['perk1','perk2','perk3','tierA','tierB']) {
            const unique = [];
            const names = new Set();
            for (const item of combined[slot]) {
                if (!names.has(item.name)) {
                    names.add(item.name);
                    unique.push(item);
                }
            }
            combined[slot] = unique;
        }
        return combined;
    }
    // Для конкретной игры
    const result = {};
    for (const slot of ['perk1','perk2','perk3','tierA','tierB']) {
        result[slot] = (perks[game] && perks[game][slot]) ? perks[game][slot].map(item => ({ ...item, game: game })) : [];
    }
    return result;
}